  OpReferralBookingUi copyWith({
    String? id,
    String? bookingDate,
    String? paymentStatus,
    bool? isCustomerReferral,
    String? referredByName,
    String? referredByPhone,
    String? orgName,
    String? patientName,
    String? patientAgeGender,
    String? patientPhone,
    String? doctorName,
    String? slotTime,
    String? bookingType,
    String? totalAmount,
    String? serviceAmount,
    String? pharmacyAmount,
    String? labAmount,
    String? feesAmount,
    String? breakdownText,
    String? customerPayable,
    String? payoutStatus,
    String? payoutPercentage,
    bool? isSettled,
    String? settledAt,
    String? serviceReceived,
    String? pharmacyReceived,
    String? labReceived,
    String? feesReceived,
    String? totalPayableAll,
    String? alreadyPaid,
    String? remainingToPay,
    Color? avatarColor,
  }) {
    return OpReferralBookingUi(
      id: id ?? this.id,
      bookingDate: bookingDate ?? this.bookingDate,
      paymentStatus: paymentStatus ?? this.paymentStatus,
      isCustomerReferral: isCustomerReferral ?? this.isCustomerReferral,
      referredByName: referredByName ?? this.referredByName,
      referredByPhone: referredByPhone ?? this.referredByPhone,
      orgName: orgName ?? this.orgName,
      patientName: patientName ?? this.patientName,
      patientAgeGender: patientAgeGender ?? this.patientAgeGender,
      patientPhone: patientPhone ?? this.patientPhone,
      doctorName: doctorName ?? this.doctorName,
      slotTime: slotTime ?? this.slotTime,
      bookingType: bookingType ?? this.bookingType,
      totalAmount: totalAmount ?? this.totalAmount,
      serviceAmount: serviceAmount ?? this.serviceAmount,
      pharmacyAmount: pharmacyAmount ?? this.pharmacyAmount,
      labAmount: labAmount ?? this.labAmount,
      feesAmount: feesAmount ?? this.feesAmount,
      breakdownText: breakdownText ?? this.breakdownText,
      customerPayable: customerPayable ?? this.customerPayable,
      payoutStatus: payoutStatus ?? this.payoutStatus,
      payoutPercentage: payoutPercentage ?? this.payoutPercentage,
      isSettled: isSettled ?? this.isSettled,
      settledAt: settledAt ?? this.settledAt,
      serviceReceived: serviceReceived ?? this.serviceReceived,
      pharmacyReceived: pharmacyReceived ?? this.pharmacyReceived,
      labReceived: labReceived ?? this.labReceived,
      feesReceived: feesReceived ?? this.feesReceived,
      totalPayableAll: totalPayableAll ?? this.totalPayableAll,
      alreadyPaid: alreadyPaid ?? this.alreadyPaid,
      remainingToPay: remainingToPay ?? this.remainingToPay,

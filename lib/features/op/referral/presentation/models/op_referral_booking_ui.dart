  final String id;
  final String bookingDate;
  final String paymentStatus;
  final bool isCustomerReferral;
  final String referredByName;
  final String referredByPhone;
  final String orgName;
  final String patientName;
  final String patientAgeGender;
  final String patientPhone;
  final String doctorName;
  final String slotTime;
  final String bookingType;
  final String totalAmount;
  final String serviceAmount;
  final String pharmacyAmount;
  final String labAmount;
  final String feesAmount;
  final String breakdownText;
  final String customerPayable;
  final String payoutStatus;
